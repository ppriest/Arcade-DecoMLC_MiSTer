"""Write rtl/video/mlc_recip_table.sv: dx = floor(2^20 / width) for width 1..256.

drawgfxzoomline's `dx = (16 << 16) / sprite_screen_width` (deco_mlc_v.cpp:62) as a table, so the
engine has no divider in the pixel path (docs/WORKFLOW.md section 14). width is at most 256: the
raster set's x scale on the entry's, both up to 0x3ff, give xs * 16 >> 16 = 255, plus one from the
fraction carry (v 56). Entry 0 is unused (v 59 draws nothing for width 0).
"""
from pathlib import Path

out = Path(__file__).resolve().parent.parent / "rtl" / "video" / "mlc_recip_table.sv"
lines = [
    "// SPDX-License-Identifier: GPL-3.0-or-later",
    "// Generated by scripts/gen_recip_table.py; do not edit. dx = floor(2^20 / width),",
    "// deco_mlc_v.cpp:62, for width 1..256 (docs/phase1_video.md). Combinational.",
    "module mlc_recip_table (",
    "\tinput  logic [8:0]  width,",
    "\toutput logic [20:0] dx",
    ");",
    "\talways_comb begin",
    "\t\tcase (width)",
]
for w in range(1, 257):
    lines.append(f"\t\t\t9'd{w}: dx = 21'h{(1 << 20) // w:06X};")
lines += [
    "\t\t\tdefault: dx = 21'd0;",
    "\t\tendcase",
    "\tend",
    "endmodule",
    "",
]
out.write_text("\n".join(lines), newline="\n")
print(out)
